"""Generate assets/divider.svg: a parchment strip with footsteps wandering across it, Marauder's Map style.

    python assets/make_divider.py

One walker crosses the whole strip; a few others wander in random directions at different times.
Positions are seeded, so the output is the same every run.
"""
import math
import random
from pathlib import Path

W, H = 1280, 70
LOOP = 8.0            # seconds before the whole scene repeats
STEP_GAP = 0.22       # seconds between footsteps
TOP, BOTTOM = 20, 52  # keep feet inside the parchment
rng = random.Random(42)


def walk(x, y, angle_deg, n, start, stride=30.0, wobble=4.0, gap=STEP_GAP):
    """Footsteps for one walker: alternating left/right feet along a slightly wandering heading."""
    steps, a = [], math.radians(angle_deg)
    for i in range(n):
        side = 5 if i % 2 else -5                       # left/right foot, perpendicular to the heading
        fx = x - math.sin(a) * side
        fy = y + math.cos(a) * side
        if TOP <= fy <= BOTTOM and 20 <= fx <= W - 20:
            steps.append((fx, fy, math.degrees(a) + 90, (start + i * gap) % LOOP))
        x += math.cos(a) * stride
        y += math.sin(a) * stride
        a += math.radians(rng.uniform(-wobble, wobble))
        if not TOP + 4 <= y <= BOTTOM - 4:              # steer back toward the middle of the strip
            a += math.radians(8 if y < (TOP + BOTTOM) / 2 else -8)
    return steps


# the main walker crosses the whole strip within one loop
steps = walk(50, 36, 0, 40, start=0.0, wobble=1.5, gap=LOOP * 0.9 / 40)
for _ in range(5):                                       # wanderers
    going_left = rng.random() < 0.5
    angle = (180 if going_left else 0) + rng.uniform(-14, 14)
    x = rng.uniform(150, W - 150)
    steps += walk(x, rng.uniform(TOP + 6, BOTTOM - 6), angle, rng.randint(6, 12),
                  start=rng.uniform(0, LOOP), stride=rng.uniform(24, 30), wobble=6)

feet = "\n".join(
    f'    <use href="#foot" class="step" transform="translate({x:.1f} {y:.1f}) rotate({r:.0f})" '
    f'style="animation-delay: {d:.2f}s"/>' for x, y, r, d in steps)

edge_top = "M8 14 L60 10 L120 15 L190 9 L260 14 L340 10 L420 15 L500 9 L590 14 L680 10 L770 15 L860 9 L950 14 L1040 10 L1130 15 L1210 10 L1272 14"
edge_bottom = "L1268 56 L1200 61 L1120 55 L1030 61 L940 56 L850 61 L760 55 L670 61 L580 56 L490 61 L400 55 L310 61 L220 56 L130 61 L60 55 L12 60 Z"

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="A parchment strip with footsteps wandering across it">
  <!-- generated by assets/make_divider.py: edit that, not this -->
  <defs>
    <linearGradient id="parch" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#efe0b4"/>
      <stop offset="0.5" stop-color="#e6d29c"/>
      <stop offset="1" stop-color="#d8bf80"/>
    </linearGradient>
    <radialGradient id="age" cx="0.5" cy="0.5" r="0.75">
      <stop offset="0.6" stop-color="#7a5a2a" stop-opacity="0"/>
      <stop offset="1" stop-color="#7a5a2a" stop-opacity="0.35"/>
    </radialGradient>
    <!-- one footprint: sole + heel, toes pointing up before rotation -->
    <g id="foot">
      <ellipse cx="0" cy="-5" rx="4.2" ry="6.5"/>
      <ellipse cx="0" cy="6" rx="3.2" ry="3.6"/>
    </g>
  </defs>

  <style>
    .step {{ opacity: 0; animation: walk {LOOP:g}s linear infinite; }}
    @keyframes walk {{
      0%   {{ opacity: 0; }}
      3%   {{ opacity: 0.9; }}
      30%  {{ opacity: 0.9; }}
      45%  {{ opacity: 0; }}
      100% {{ opacity: 0; }}
    }}
  </style>

  <!-- torn-edge parchment strip -->
  <path d="{edge_top}
           {edge_bottom}" fill="url(#parch)"/>
  <path d="{edge_top}
           {edge_bottom}" fill="url(#age)"/>

  <!-- faint dotted trail of the main walker -->
  <path d="M40 36 H1240" stroke="#5a3e1b" stroke-opacity="0.2" stroke-width="1.5" stroke-dasharray="2 9"/>

  <!-- footsteps, each appearing in turn -->
  <g fill="#4a3216">
{feet}
  </g>
</svg>
'''

out = Path(__file__).with_name("divider.svg")
out.write_text(svg, encoding="utf-8", newline="\n")
print(f"wrote {out}: {len(steps)} footsteps")
