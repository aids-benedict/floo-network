"""Generate assets/divider.svg: two castle silhouettes under a starry sky, with a green Floo spark
travelling between them (a message going from one hearth to another).

    python assets/make_divider.py
"""
import random
from pathlib import Path

W, H, GROUND = 1280, 120, 112
TOWER_SCALE = 0.85
rng = random.Random(3)
SIL = "#06050b"                 # silhouette colour


def tower(x, w, h, roof="cone"):
    """A tower standing on the ground at x (left edge). Returns (svg parts, top point for the arc)."""
    h = h * TOWER_SCALE
    top = GROUND - h
    parts = [f'<rect x="{x}" y="{top:.1f}" width="{w}" height="{h:.1f}" fill="{SIL}"/>']
    if roof == "cone":
        rh = w * 1.3
        parts.append(f'<path d="M{x - 2} {top:.1f} L{x + w / 2} {top - rh:.1f} L{x + w + 2} {top:.1f} Z" fill="{SIL}"/>')
        apex = (x + w / 2, top - rh)
        parts.append(f'<path d="M{apex[0]} {apex[1]:.1f} v-7 l7 2.5 l-7 2.5" fill="{SIL}" stroke="{SIL}" stroke-width="1"/>')
    else:  # battlements
        n = max(2, int(w // 6))
        step = w / n
        for i in range(0, n, 2):
            parts.append(f'<rect x="{x + i * step:.1f}" y="{top - 5:.1f}" width="{step:.1f}" height="5" fill="{SIL}"/>')
        apex = (x + w / 2, top - 5)
    for wy in range(int(top) + 8, GROUND - 6, 13):  # windows
        if rng.random() < 0.55:
            colour = "#5dff8f" if rng.random() < 0.3 else "#ffcf6b"
            delay = rng.uniform(0, 6)
            parts.append(f'<rect class="win" x="{x + w / 2 - 1.5:.1f}" y="{wy}" width="3" height="5" rx="1" '
                         f'fill="{colour}" style="animation-delay:-{delay:.1f}s"/>')
    return parts, apex


def wall(x0, x1, h):
    top = GROUND - h
    parts = [f'<rect x="{x0}" y="{top}" width="{x1 - x0}" height="{h}" fill="{SIL}"/>']
    x = x0
    while x < x1 - 4:
        parts.append(f'<rect x="{x}" y="{top - 4}" width="4" height="4" fill="{SIL}"/>')
        x += 8
    return parts


def castle(x, flip=False):
    """A small castle about 260px wide. Returns (parts, arc anchor at the tallest tower)."""
    spec = [  # (dx, width, height, roof)
        (0, 18, 34, "flat"), (30, 22, 50, "cone"), (70, 30, 66, "cone"),
        (116, 20, 44, "flat"), (150, 26, 56, "cone"), (196, 16, 30, "cone"), (226, 22, 40, "flat"),
    ]
    if flip:
        spec = [(248 - dx - w, w, h, r) for dx, w, h, r in spec]
    parts = wall(x + 8, x + 240, 22)
    anchor, best = None, -1
    for dx, w, h, roof in spec:
        p, apex = tower(x + dx, w, h, roof)
        parts += p
        if h > best:
            best, anchor = h, apex
    parts.append(f'<path d="M{x + 108} {GROUND} v-8 a4 4 0 0 1 8 0 v8 Z" fill="#ffcf6b" opacity="0.7"/>')  # lit gate
    return parts, anchor


left, a = castle(40)
right, b = castle(W - 300, flip=True)
# from the tallest tower of one castle to the other's, arching over the sky (apex ~18px from the top)
arc = f"M{a[0]:.1f} 64 Q{W / 2} -30, {b[0]:.1f} 64"

stars = []
for _ in range(70):
    sx, sy, r = rng.uniform(10, W - 10), rng.uniform(6, 80), rng.choice([0.6, 0.8, 1.0, 1.3])
    stars.append(f'<circle class="star" cx="{sx:.0f}" cy="{sy:.0f}" r="{r}" '
                 f'style="animation-delay:-{rng.uniform(0, 4):.1f}s; animation-duration:{rng.uniform(2.5, 5):.1f}s"/>')

hills = (f"M0 {GROUND} C200 {GROUND - 8} 380 {GROUND - 2} 640 {GROUND - 6} "
         f"C900 {GROUND - 10} 1080 {GROUND - 2} {W} {GROUND - 7} V{H} H0 Z")

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="Two castles under a starry sky, a green spark flying between them">
  <!-- generated by assets/make_divider.py: edit that, not this -->
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#070a18"/>
      <stop offset="0.7" stop-color="#151230"/>
      <stop offset="1" stop-color="#2a1c3a"/>
    </linearGradient>
    <radialGradient id="spark" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="#ffffff"/>
      <stop offset="0.3" stop-color="#7dffa6"/>
      <stop offset="1" stop-color="#2ee86a" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="moonGlow" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0.3" stop-color="#f3ecd2" stop-opacity="0.12"/>
      <stop offset="1" stop-color="#f3ecd2" stop-opacity="0"/>
    </radialGradient>
    <mask id="crescent" maskUnits="userSpaceOnUse" x="770" y="4" width="60" height="60">
      <circle cx="800" cy="34" r="13" fill="#fff"/>
      <circle cx="806" cy="30" r="12" fill="#000"/>
    </mask>
    <clipPath id="strip"><rect width="{W}" height="{H}" rx="10"/></clipPath>
  </defs>
  <style>
    .star {{ fill: #e8ecff; animation: twinkle 3s ease-in-out infinite alternate; }}
    @keyframes twinkle {{ from {{ opacity: 0.15; }} to {{ opacity: 0.95; }} }}
    .win {{ animation: flicker 5s steps(1) infinite; }}
    @keyframes flicker {{ 0% {{ opacity: 0.95; }} 47% {{ opacity: 0.6; }} 52% {{ opacity: 0.95; }} 81% {{ opacity: 0.75; }} }}
  </style>

  <g clip-path="url(#strip)">
    <rect width="{W}" height="{H}" fill="url(#sky)"/>
    {chr(10).join("    " + s for s in stars)}
    <!-- crescent moon -->
    <circle cx="800" cy="34" r="30" fill="url(#moonGlow)"/>
    <circle cx="800" cy="34" r="13" fill="#f3ecd2" opacity="0.9" mask="url(#crescent)"/>
    <!-- the Floo route between the two castles -->
    <path d="{arc}" fill="none" stroke="#d3a625" stroke-opacity="0.6" stroke-width="1.6" stroke-dasharray="2.5 7"/>
    <circle r="7" fill="url(#spark)">
      <animateMotion dur="5s" repeatCount="indefinite" path="{arc}" keyPoints="0;1;1" keyTimes="0;0.7;1" calcMode="linear"/>
      <animate attributeName="opacity" dur="5s" values="0;1;1;0;0" keyTimes="0;0.06;0.64;0.7;1" repeatCount="indefinite"/>
    </circle>
    <path d="{hills}" fill="#0d0b16"/>
    {chr(10).join("    " + s for s in left)}
    {chr(10).join("    " + s for s in right)}
  </g>
</svg>
'''

out = Path(__file__).with_name("divider.svg")
out.write_text(svg, encoding="utf-8", newline="\n")
print(f"wrote {out} ({len(svg) // 1024} KB)")
