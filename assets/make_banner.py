W, H = 1280, 420
CX = 640                       # fireplace centre
STONE, STONE_LIGHT = "#4f4842", "#5c534b"   # dark, firelit stone: the green light does the brightening
rng = random.Random(7)


def shade(base, spread):
    r, g, b = (int(base[i:i + 2], 16) for i in (1, 3, 5))
    k = rng.uniform(-spread, spread)
    tint = rng.uniform(-spread / 3, spread / 3)
    clamp = lambda v: max(0, min(255, int(v)))
    return f"#{clamp(r * (1 + k + tint)):02x}{clamp(g * (1 + k)):02x}{clamp(b * (1 + k - tint)):02x}"


def bricks():
    """Running-bond wall bricks with jittered sizes and tones."""
    out, bh, y, row = [], 26, -6, 0
    while y < H:
        x = -rng.randint(0, 60) if row % 2 else -rng.randint(20, 40)
        while x < W:
            bw = rng.randint(54, 74)
            out.append(f'<rect x="{x + 1.5:.1f}" y="{y + 1.5:.1f}" width="{bw - 3}" height="{bh - 3}" rx="2.5" '
                       f'fill="{shade("#3b2c24", 0.22)}"/>')
            x += bw
        y += bh
        row += 1
    return "\n    ".join(out)


def side_stones(x0, x1):
    """Large dressed stones stacked up one side of the fireplace."""
    out, y = [], 192
    while y < 408:
        h = rng.randint(44, 58)
        h = min(h, 408 - y)
        out.append(f'<rect x="{x0}" y="{y + 1}" width="{x1 - x0}" height="{h - 2}" rx="3" fill="{shade(STONE, 0.13)}"/>')
        out.append(f'<rect x="{x0}" y="{y + 1}" width="{x1 - x0}" height="{h - 2}" rx="3" fill="url(#bevel)"/>')
        y += h
    return out


def spandrel_stones():
    """Blocks filling the space between the arch and the mantel (drawn under the arch ring)."""
    out, x = [], 452
    widths = [62, 58, 66, 70, 60, 64]
    for i, w in enumerate(widths):
        w = min(w, 828 - x) if i < len(widths) - 1 else 828 - x
        for y, h in ((194, 34), (228, 36)):
            out.append(f'<rect x="{x + 1}" y="{y + 1}" width="{w - 2}" height="{h - 2}" rx="2.5" fill="{shade(STONE, 0.13)}"/>')
            out.append(f'<rect x="{x + 1}" y="{y + 1}" width="{w - 2}" height="{h - 2}" rx="2.5" fill="url(#bevel)"/>')
        x += w
    return out


def arch_stones():
    """Wedge-shaped voussoirs around the arch opening."""
    out, cy, rx_in, ry_in, rx_out, ry_out = [], 262, 120, 62, 146, 88
    n = 11
    for i in range(n):
        a0 = math.pi - math.pi * i / n
        a1 = math.pi - math.pi * (i + 1) / n
        pts = [(CX + rx_in * math.cos(a0), cy - ry_in * math.sin(a0)),
               (CX + rx_out * math.cos(a0), cy - ry_out * math.sin(a0)),
               (CX + rx_out * math.cos(a1), cy - ry_out * math.sin(a1)),
               (CX + rx_in * math.cos(a1), cy - ry_in * math.sin(a1))]
        d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + " Z"
        out.append(f'<path d="{d}" fill="{shade(STONE_LIGHT, 0.1)}" stroke="#15110e" stroke-width="2.5" stroke-linejoin="round"/>')
    return out


def firebox_bricks():
    out = []
