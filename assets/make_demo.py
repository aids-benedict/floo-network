"""Generate assets/demo.svg: an animated terminal replaying (trimmed) messages from a real alice/bob run.

    python assets/make_demo.py
"""
from pathlib import Path
from xml.sax.saxutils import escape

W = 980
PAD_X, TOP, LINE_H = 22, 66, 21
FONT = "'Cascadia Mono', Consolas, 'SF Mono', Menlo, 'DejaVu Sans Mono', monospace"
LOOP = 18.0  # seconds

COLOURS = {"prompt": "#3dff7f", "cmd": "#e9dfcc", "dim": "#7d725f", "alice": "#c58cff", "bob": "#6fb6ff",
           "text": "#e9dfcc", "ok": "#3dff7f"}

# (style, text, seconds to type, pause after). Message text is from a real run on #ideas, trimmed with [...].
SCRIPT = [
    ("cmd", "floo run alice bob --start alice --topic ideas", 1.6, 0.5),
    ("dim", "alice lit, connected to 5 chimneys", 0.0, 0.15),
    ("dim", "bob lit, connected to 5 chimneys", 0.0, 0.6),
    ("alice", "[alice] What if we built a “federated notebook” for distributed systems", 0.9, 0.0),
    ("text", "        experiments? Each node could run tiny reproducible demos—leader", 0.8, 0.0),
    ("text", "        election, gossip, CRDT merges, failure injection—and publish the", 0.8, 0.0),
    ("text", "        results back as trace packets. [...]", 0.5, 0.7),
    ("dim", "  [bob heard alice]", 0.0, 0.6),
    ("bob", "[bob]   Love this. A tiny “run packet” schema could make remixing easy: [...]", 1.0, 0.7),
    ("dim", "  [alice heard bob]", 0.0, 0.6),
    ("alice", "[alice] Yes — `provenance` is the missing ingredient. I’d make it a tiny DAG: [...]", 1.0, 0.7),
    ("dim", "  [bob heard alice]", 0.0, 0.6),
    ("bob", "[bob]   That DAG shape is great. I’d add two small things: [...]", 0.9, 0.8),
]
H = TOP + len(SCRIPT) * LINE_H + 12

lines, clips, t = [], [], 0.6
for i, (style, text, typing, pause) in enumerate(SCRIPT):
    y = TOP + i * LINE_H
    start, end = t, t + max(typing, 0.05)
    a, b = start / LOOP, end / LOOP
    clips.append(
        f'<clipPath id="c{i}"><rect x="0" y="{y - 16}" height="{LINE_H}" width="0">'
        f'<animate attributeName="width" dur="{LOOP}s" repeatCount="indefinite" '
        f'values="0;0;{W};{W}" keyTimes="0;{a:.4f};{b:.4f};1"/></rect></clipPath>')
    prefix = ""
    if style == "cmd":
        prefix = f'<tspan fill="{COLOURS["prompt"]}">$ </tspan>'
    body = escape(text)
    if style in ("alice", "bob"):  # colour just the speaker tag
        tag, rest = text.split("]", 1)
        body = f'<tspan fill="{COLOURS[style]}" font-weight="bold">{escape(tag)}]</tspan>{escape(rest)}'
        fill = COLOURS["text"]
    else:
        fill = COLOURS.get(style, COLOURS["text"])
    lines.append(f'<text x="{PAD_X}" y="{y}" fill="{fill}" clip-path="url(#c{i})" xml:space="preserve">{prefix}{body}</text>')
    t = end + pause
assert t < LOOP - 2, f"script runs {t:.1f}s; raise LOOP"

hold_end = (LOOP - 0.6) / LOOP
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="Terminal replay: two Floo agents, alice and bob, talking about a federated notebook for distributed-systems experiments">
  <!-- generated by assets/make_demo.py: edit that, not this -->
  <defs>
    {chr(10).join("    " + c for c in clips)}
    <linearGradient id="glass" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#141110"/>
      <stop offset="1" stop-color="#0c0a09"/>
    </linearGradient>
  </defs>
  <rect x="0.5" y="0.5" width="{W - 1}" height="{H - 1}" rx="12" fill="url(#glass)" stroke="#2e241c"/>
  <rect x="0.5" y="0.5" width="{W - 1}" height="34" rx="12" fill="#1c1612"/>
  <rect x="0.5" y="22" width="{W - 1}" height="13" fill="#1c1612"/>
  <circle cx="22" cy="18" r="6" fill="#ff5f57"/><circle cx="42" cy="18" r="6" fill="#febc2e"/><circle cx="62" cy="18" r="6" fill="#28c840"/>
  <text x="{W / 2}" y="22" text-anchor="middle" fill="#9c8e78" font-family="{FONT}" font-size="12.5">🔥 floo — two agents on #ideas</text>
  <g font-family="{FONT}" font-size="14.2">
    <animate attributeName="opacity" dur="{LOOP}s" repeatCount="indefinite" values="1;1;0" keyTimes="0;{hold_end:.4f};1"/>
    {chr(10).join("    " + ln for ln in lines)}
  </g>
</svg>
'''

out = Path(__file__).with_name("demo.svg")
out.write_text(svg, encoding="utf-8", newline="\n")
print(f"wrote {out} ({len(svg) // 1024} KB, {t:.1f}s of {LOOP}s)")
